const inMemoryTranslationVault = new Map();

/**
 * Resolves UI translation with AI-first and static fallback.
 */
export async function getAiUiTranslation(targetLanguage = "en") {
  const normLang = String(targetLanguage || "en").toLowerCase().trim();

  // 1. If static native dictionary exists, use it as baseline
  if (STATIC_UI_DICTIONARY[normLang]) {
    return STATIC_UI_DICTIONARY[normLang];
  }

  // 2. Check in-memory vault
  if (inMemoryTranslationVault.has(normLang)) {
    return inMemoryTranslationVault.get(normLang);
  }

  // 3. Check database cache
  try {
    const dbCached = await getUiTranslation(normLang);
    if (dbCached && typeof dbCached === "object") {
      inMemoryTranslationVault.set(normLang, dbCached);
      return dbCached;
    }
  } catch (err) {
    console.warn("DB UI translation check failed:", err.message);
  }

  // 4. AI-Powered Dynamic Generation
  try {
    const prompt = `Translate the following JSON dictionary of UI buttons and labels into natural, idiomatic ${targetLanguage}.
CRITICAL RULES:
- Keep translation concise, modern, and user-friendly.
- Return ONLY valid JSON with the exact same keys.
- Preserve technical terms like 3D, PDF, AI, CEFR, Telegram.
${JSON.stringify(STATIC_UI_DICTIONARY.en, null, 2)}`;

    const responseText = await withModelFallback(prompt, {
      systemInstruction: "You are a professional localization and UI translation engine. Return strictly raw JSON.",
      responseMimeType: "application/json"
    });

    const parsed = JSON.parse(responseText.trim());
    if (parsed && typeof parsed === "object") {
      inMemoryTranslationVault.set(normLang, parsed);
      saveUiTranslation(normLang, parsed).catch(() => {});
      return parsed;
    }
  } catch (err) {
    console.warn(`AI UI translation for ${normLang} failed, using English fallback:`, err.message);
  }

  // 5. Ultimate safe fallback: English static dictionary
  return STATIC_UI_DICTIONARY.en;
}
