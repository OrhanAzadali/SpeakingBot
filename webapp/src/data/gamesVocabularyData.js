// Helper to filter words by target language and level
export function getVocabularyForGame(targetLanguage = 'English', level = 'ALL', count = 12) {
  const normLang = (targetLanguage || 'English').toLowerCase();
  let matches = GAMES_VOCABULARY.filter(v => v.language.toLowerCase() === normLang);
  
  // Fallback to English if very few entries for requested language
  if (matches.length < 4 && normLang !== 'english') {
    matches = [...matches, ...GAMES_VOCABULARY.filter(v => v.language.toLowerCase() === 'english')];
  }

  if (level !== 'ALL') {
    const levelFiltered = matches.filter(v => v.level === level);
    if (levelFiltered.length >= 4) {
      matches = levelFiltered;
    }
  }

  // Shuffle and slice
  const shuffled = [...matches].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
