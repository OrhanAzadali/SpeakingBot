export function normalizeUiLang(codeOrName) {
  if (!codeOrName) return 'en';
  const low = String(codeOrName).toLowerCase();
  if (low.startsWith('az')) return 'az';
  if (low.startsWith('ru')) return 'ru';
  if (low.startsWith('tr')) return 'tr';
  if (low.startsWith('es') || low.includes('span')) return 'es';
  if (low.startsWith('de') || low.includes('germ')) return 'de';
  return 'en';
}

export function normalizeTargetLang(lang) {
  if (!lang) return 'english';
  const low = String(lang).toLowerCase();
  if (low.includes('russ')) return 'russian';
  if (low.includes('span')) return 'spanish';
  if (low.includes('germ') || low.includes('deutsch')) return 'german';
  if (low.includes('fren') || low.includes('français')) return 'french';
  if (low.includes('ital')) return 'italian';
  return 'english';
}

