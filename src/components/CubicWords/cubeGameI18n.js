export function getLocalizedComboWord(targetLanguage, mediatorLanguage, wordCandidate = null) {
  const tLang = normalizeTargetLang(targetLanguage);
  const mCode = normalizeUiLang(mediatorLanguage);
  const list = LOCALIZED_TARGET_WORDS[tLang] || LOCALIZED_TARGET_WORDS.english;

  let item = list[0];
  if (wordCandidate) {
    const found = list.find((q) => q.word.toUpperCase() === wordCandidate.toUpperCase());
    if (found) item = found;
  }

  const mData = item.meanings[mCode] || item.meanings.en;
  return {
    word: item.word,
    emoji: item.emoji,
    meaning: mData.meaning,
    hint: mData.hint,
  };
}
