    paragraphs: [sentences.join(" ")],
    sentences: sentences.map((s, idx) => ({
      text: s,
      translation: translations[idx] || "",
      literaryNote: literaryNotes[idx] || "",
      audioTime: `0:${String(idx * 7).padStart(2, "0")} - 0:${String((idx + 1) * 7).padStart(2, "0")}`
    })),
